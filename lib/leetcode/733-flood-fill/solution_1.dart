class Solution {
  List<List<int>> floodFill(List<List<int>> image, int sr, int sc, int color) {
    final r_color = image[sr][sc];

    if (r_color == color) return image;

    final w = image[0].length;
    final h = image.length;

    final queues = Queue<(int, int)>();

    void a2q((int, int) e) {
      image[e.$1][e.$2] = color;
      queues.add((e.$1, e.$2));
    }

    a2q((sr, sc));

    while (queues.isNotEmpty) {
      final (r, c) = queues.removeFirst();

      if (c > 0 && image[r][c - 1] == r_color) a2q((r, c - 1));
      if (r > 0 && image[r - 1][c] == r_color) a2q((r - 1, c));
      if (c < w - 1 && image[r][c + 1] == r_color) a2q((r, c + 1));
      if (r < h - 1 && image[r + 1][c] == r_color) a2q((r + 1, c));
    }

    return image;
  }
}

